export const service_account = pgTable("service_account", {
  id: text("id").primaryKey(),
  name: text("name").notNull(),
  scopes: text("scopes").array().notNull(),
  created_at: timestamp("created_at").defaultNow(),
  updated_at: timestamp("updated_at")
    .defaultNow()
    .$onUpdate(() => new Date()),
});

export const service_key = pgTable(
  "service_key",
  {
    id: text("id").primaryKey(),
    service_account_id: text("service_account_id")
      .notNull()
      .references(() => service_account.id, { onDelete: "cascade" }),
    key: text("key").notNull(),
    metadata: text("metadata"),
    expiresAt: timestamp("expires_at"),
    created_at: timestamp("created_at").defaultNow(),
    updated_at: timestamp("updated_at")
      .defaultNow()
      .$onUpdate(() => new Date()),
  },
  (table) => [index("service_key_key_idx").on(table.key)],
);

export const userRelations = relations(user, ({ many }) => ({
  sessions: many(session),
  accounts: many(account),
}));

export const sessionRelations = relations(session, ({ one }) => ({
  user: one(user, {
    fields: [session.userId],
    references: [user.id],
  }),
}));

export const accountRelations = relations(account, ({ one }) => ({
  user: one(user, {
    fields: [account.userId],
    references: [user.id],
  }),
}));

export const service_accountRelations = relations(
  service_account,
  ({ many }) => ({
    service_keys: many(service_key),
  }),
);

export const service_keyRelations = relations(service_key, ({ one }) => ({
  service_account: one(service_account, {
    fields: [service_key.service_account_id],
    references: [service_account.id],
  }),
}));
