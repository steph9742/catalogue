export type FieldType = 'text' | 'textarea' | 'number' | 'date' | 'checkbox' | 'select' | 'multiselect' | 'ref'

export type CatalogueField = {
  key: string
  label: string
  type: FieldType
  required?: boolean
  options?: EnumOption[] // select
  endpoint?: string // ref → catalogue cible
  labelKey?: string // ref → propriété à afficher
  placeholder?: string
  autreKey?: string // select : clé du champ texte libre associé à l'option « Autre »
  autreValue?: string // valeur déclenchant le champ libre (défaut 'autre')
  // Champ conditionnel : visible seulement si l'une des conditions est vraie (OU logique).
  showIf?: { key: string, value: string }[]
}

export type CatalogueColumn = {
  key: string
  label: string
  options?: EnumOption[] // rendu du libellé d'enum
  bool?: boolean // rendu oui/non
  autreKey?: string // colonne texte de précision pour l'option « Autre »
}

export type CatalogueConfig = {
  key: string // segment de route
  endpoint: string // chemin API
  label: string
  singular: string
  naturalKey: string
  icon: string
  columns: CatalogueColumn[]
  fields: CatalogueField[]
  // Colonnes d'import supplémentaires résolues par nom côté serveur (entités liées
  // créées/liées à la volée) : ex. « Responsable » → crée/lie une personne.
  importRefs?: { key: string, label: string }[]
  // Pagination SERVEUR : pour les catalogues volumineux (parc machines ~9000), la liste charge
  // page par page au lieu de tout ramener.
  paginated?: boolean
}

